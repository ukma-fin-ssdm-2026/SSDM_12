-- Frozen initial schema (0001).

CREATE EXTENSION IF NOT EXISTS btree_gist;


CREATE TABLE app_user (
	id UUID NOT NULL,
	full_name TEXT NOT NULL,
	email TEXT NOT NULL,
	PRIMARY KEY (id)
)

;

CREATE UNIQUE INDEX uq_user_email_lower ON app_user (lower(email));


CREATE TABLE booking_policy (
	id UUID NOT NULL,
	booking_limit INTEGER NOT NULL,
	cancel_window_minutes INTEGER NOT NULL,
	PRIMARY KEY (id),
	CHECK (booking_limit > 0 AND cancel_window_minutes >= 0)
)

;


CREATE TABLE audit_log (
	id UUID NOT NULL,
	seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
	actor_id UUID NOT NULL,
	action TEXT NOT NULL,
	object_id UUID,
	before JSONB,
	after JSONB,
	at TIMESTAMP WITH TIME ZONE NOT NULL,
	PRIMARY KEY (id),
	UNIQUE (seq),
	FOREIGN KEY(actor_id) REFERENCES app_user (id)
)

;


CREATE TABLE current_policy (
	singleton SERIAL NOT NULL,
	policy_id UUID NOT NULL,
	PRIMARY KEY (singleton),
	CHECK (singleton=1),
	FOREIGN KEY(policy_id) REFERENCES booking_policy (id)
)

;


CREATE TABLE user_role (
	user_id UUID NOT NULL,
	role VARCHAR(16) NOT NULL,
	PRIMARY KEY (user_id, role),
	CHECK (role IN ('student','provider','admin')),
	FOREIGN KEY(user_id) REFERENCES app_user (id)
)

;


CREATE TABLE resource (
	id UUID NOT NULL,
	name TEXT NOT NULL,
	type VARCHAR(16) NOT NULL,
	capacity INTEGER,
	provider_id UUID NOT NULL,
	provider_role VARCHAR(16) DEFAULT 'provider' NOT NULL,
	PRIMARY KEY (id),
	CHECK (provider_role = 'provider'),
	CHECK ((type='room' AND capacity IS NOT NULL AND capacity BETWEEN 1 AND 1000) OR (type='consultation' AND capacity IS NULL)),
	FOREIGN KEY(provider_id, provider_role) REFERENCES user_role (user_id, role) DEFERRABLE INITIALLY DEFERRED
)

;


CREATE TABLE availability_template (
	id UUID NOT NULL,
	resource_id UUID NOT NULL,
	weekday INTEGER NOT NULL,
	start_local TIME WITHOUT TIME ZONE NOT NULL,
	end_local TIME WITHOUT TIME ZONE NOT NULL,
	slot_minutes INTEGER NOT NULL,
	valid_from DATE NOT NULL,
	valid_to DATE,
	PRIMARY KEY (id),
	CHECK (weekday BETWEEN 1 AND 7 AND end_local > start_local AND slot_minutes > 0),
	CHECK (valid_to IS NULL OR valid_to >= valid_from),
	FOREIGN KEY(resource_id) REFERENCES resource (id)
)

;


CREATE TABLE time_block (
	id UUID NOT NULL,
	resource_id UUID NOT NULL,
	starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
	ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
	reason TEXT NOT NULL,
	PRIMARY KEY (id),
	CHECK (ends_at > starts_at AND length(trim(reason)) > 0),
	FOREIGN KEY(resource_id) REFERENCES resource (id)
)

;


CREATE TABLE slot (
	id UUID NOT NULL,
	resource_id UUID NOT NULL,
	template_id UUID,
	starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
	ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
	is_active BOOLEAN DEFAULT true NOT NULL,
	PRIMARY KEY (id),
	CHECK (ends_at > starts_at),
	FOREIGN KEY(resource_id) REFERENCES resource (id),
	FOREIGN KEY(template_id) REFERENCES availability_template (id),
	CONSTRAINT ex_slot_active_overlap EXCLUDE USING gist (resource_id WITH =, tstzrange(starts_at, ends_at, '[)') WITH &&) WHERE (slot.is_active) DEFERRABLE INITIALLY DEFERRED
)

;


CREATE TABLE booking (
	id UUID NOT NULL,
	slot_id UUID NOT NULL,
	student_id UUID NOT NULL,
	status VARCHAR(16) NOT NULL,
	policy_id UUID NOT NULL,
	cancel_deadline_at TIMESTAMP WITH TIME ZONE NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE NOT NULL,
	cancelled_at TIMESTAMP WITH TIME ZONE,
	cancelled_by UUID,
	cancellation_kind VARCHAR(32),
	cancellation_reason TEXT,
	rescheduled_to_id UUID,
	PRIMARY KEY (id),
	UNIQUE (rescheduled_to_id),
	CHECK (status IN ('confirmed','cancelled')),
	CHECK ((cancellation_kind IS NOT DISTINCT FROM 'rescheduled') = (rescheduled_to_id IS NOT NULL)),
	CHECK (status <> 'cancelled' OR (cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL AND cancellation_kind IS NOT NULL)),
	CHECK (cancellation_kind IS NULL OR cancellation_kind IN ('student','provider_block','rescheduled')),
	CHECK (cancellation_kind <> 'provider_block' OR (cancellation_reason IS NOT NULL AND length(trim(cancellation_reason)) > 0)),
	FOREIGN KEY(slot_id) REFERENCES slot (id),
	FOREIGN KEY(student_id) REFERENCES app_user (id),
	FOREIGN KEY(policy_id) REFERENCES booking_policy (id),
	FOREIGN KEY(cancelled_by) REFERENCES app_user (id),
	FOREIGN KEY(rescheduled_to_id) REFERENCES booking (id) DEFERRABLE INITIALLY DEFERRED
)

;

CREATE UNIQUE INDEX uq_booking_slot_confirmed ON booking (slot_id) WHERE status = 'confirmed';


CREATE TABLE idempotency (
	student_id UUID NOT NULL,
	key VARCHAR(64) NOT NULL,
	slot_id UUID NOT NULL,
	booking_id UUID NOT NULL,
	PRIMARY KEY (student_id, key),
	FOREIGN KEY(student_id) REFERENCES app_user (id),
	FOREIGN KEY(slot_id) REFERENCES slot (id),
	FOREIGN KEY(booking_id) REFERENCES booking (id)
)

;


CREATE TABLE notification (
	id UUID NOT NULL,
	booking_id UUID NOT NULL,
	recipient_id UUID NOT NULL,
	kind VARCHAR(32) NOT NULL,
	payload JSONB NOT NULL,
	scheduled_for TIMESTAMP WITH TIME ZONE NOT NULL,
	status VARCHAR(16) NOT NULL,
	attempts INTEGER NOT NULL,
	locked_until TIMESTAMP WITH TIME ZONE,
	claim_token UUID,
	sent_at TIMESTAMP WITH TIME ZONE,
	last_error VARCHAR(64),
	PRIMARY KEY (id),
	CHECK (status IN ('pending','sending','sent','failed','cancelled') AND attempts >= 0),
	FOREIGN KEY(booking_id) REFERENCES booking (id),
	FOREIGN KEY(recipient_id) REFERENCES app_user (id)
)

;

CREATE INDEX ix_notification_due ON notification (status, scheduled_for);


CREATE TABLE notification_delivery (
	id UUID NOT NULL,
	recipient_id UUID NOT NULL,
	kind VARCHAR(32) NOT NULL,
	payload JSONB NOT NULL,
	delivered_at TIMESTAMP WITH TIME ZONE NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY(id) REFERENCES notification (id),
	FOREIGN KEY(recipient_id) REFERENCES app_user (id)
)

;
