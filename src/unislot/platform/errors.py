"""Базовий клас доменних помилок (HLD §9, «Помилки»).

Доменна помилка описує порушення правила мовою предметної області: «слот уже
зайнятий», «граничний час скасування минув». Вона не знає ні про HTTP, ні про
FastAPI. Шар `REST API` перекладає її у відповідь RFC 9457 за кодом `code`
(обробник `_on_domain_error` в `api.errors`), тож статуси, назви й дії для
користувача живуть в одному каталозі `api.errors.CATALOG` (DD-07), а домен
тестується без веб-фреймворку.
"""

from __future__ import annotations

from typing import Any, ClassVar


class DomainError(Exception):
    """Порушення доменного правила.

    Підклас задає `code` — стабільний машинний код причини, той самий рядок, що й
    у каталозі помилок API. Екземпляр несе `detail` — пояснення саме цього випадку —
    і `context` — дані, які допоможуть клієнту (наприклад, ліміт і поточну кількість).

    Attributes:
        code: Машинний код причини. Базовий клас дає `INTERNAL_ERROR`: помилка без
            власного коду стає відповіддю 500 без деталей, а не «тихим» успіхом.
        detail: Пояснення для людини; None — узяти типовий опис коду з каталогу.
        context: Додаткові поля відповіді. Ключі мають бути оголошені в моделі
            `api.errors.Problem`, інакше REST API їх відкине.
    """

    code: ClassVar[str] = "INTERNAL_ERROR"

    def __init__(self, detail: str | None = None, **context: Any) -> None:
        """Створює помилку з поясненням і необов'язковими даними для клієнта."""
        self.detail = detail
        self.context = context
        super().__init__(f"{self.code}: {detail}" if detail else self.code)
